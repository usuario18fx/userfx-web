import assert from "node:assert/strict";
import { sendAccessNotice } from "../lib/access-notices.js";
const records = new Map();
const redis = { async set(k,v,...o) {if(o.includes("NX")&&records.has(k))return null; records.set(k,v); return "OK";}, async del(k){records.delete(k);} };
let sends=0;
const args={redis,namespace:"test",username:"chosen",access:{enabled:true,telegramfx_access:true},siteUrl:"https://user18fx.com",resolveRecipient:async()=>"123456",telegram:{async sendMessage(id,text,options){sends++;assert.equal(id,"123456");assert.match(text,/granted access/);assert.equal(options.reply_markup.inline_keyboard[0][0].url,"https://user18fx.com/#/private-room-access");return {message_id:9};}}};
assert.equal(await sendAccessNotice({...args,access:{enabled:false}}),"inactive");
assert.equal(await sendAccessNotice({...args,resolveRecipient:async()=>null}),"unreachable");
assert.equal(sends,0);
assert.deepEqual((await Promise.all([sendAccessNotice(args),sendAccessNotice(args)])).sort(),["already","sent"]);
assert.equal(sends,1);
records.clear();
assert.equal(await sendAccessNotice({...args,telegram:{async sendMessage(){throw {response:{error_code:403}};}}}),"blocked");
assert.equal(records.size,0);
assert.equal(await sendAccessNotice({...args,telegram:{async sendMessage(){throw Error("timeout");}}}),"uncertain");
assert.equal(await sendAccessNotice(args),"already");
console.log("PASS: active and verified recipients, concurrent deduplication, blocked users and uncertain delivery.");
